#!/usr/bin/env python3
"""Generate the native-extra-page prefill module (DSV41_PREFILL_NATIVE_EXTRA) from FlashInfer's own sources.

Why: the stock SM120 sparse-MLA prefill reads the extra (compressed) cache only with 64- or 2-token pages, so
runtime/flash_mla_sm120.canary.py splits SGLang's 128/256-token extra pages into a persistent 64-token copy of the
WHOLE extra pool (`_split_kv_pages_to_64(..., buffer_tag="extra")`, N x ratio x 37,440 B, ~2.98 GB per rank at the
v2.6 pool). The kernel itself is generic in PAGE_BLOCK_SIZE_EXTRA (all address math is
`(size_t)(idx / PBS) * stride_kv_block + (idx % PBS) * 576`, scales at `PBS * 576 + (idx % PBS) * 8`, and the only
PBSX-specific branch is the PBSX == 2 row XOR); only the host dispatch is closed. This generator copies the installed
FlashInfer's prefill dispatch and orchestrator, opens the dual-cache dispatch to extra pages of 128 and 256 tokens
(and ONLY those: 64 / 2 stay on the stock module), drops the single-cache paths, and renames the two external
symbols so the module can sit next to the stock one. No kernel header is copied or changed: the module compiles
against the image's own flashinfer/attention/sparse_mla_sm120 headers.

Fail-closed (REVIEW_sol K8 P2-1): before any edit, the COMPLETE source closure the module compiles from -- the two
FlashInfer .cu inputs, the TVM-FFI glue header and layout.cuh it includes, and every file of
include/flashinfer/attention/sparse_mla_sm120/ (the kernels; they include nothing else outside the CUDA toolkit) -- must
equal APPROVED_CLOSURE.json file for file and byte for byte (same file set, same sha256). Anchors alone would accept an
unanchored statement or a kernel header that changed. Every edit is then an exact anchor that must occur exactly once
(or the stated count). The manifest records the closure, and the module tag covers it as well as the generated
translation units, so a module built from another closure has another name. Qualifying another FlashInfer revision
means reviewing its closure and committing a new APPROVED_CLOSURE.json (`--approve`), never just re-running this.

    gen_pce_sources.py CSRC_DIR INCLUDE_DIR OUT_DIR             generate (refuses an unapproved closure)
    gen_pce_sources.py --approve CSRC_DIR INCLUDE_DIR           print the closure JSON of these directories
CSRC_DIR / INCLUDE_DIR: FlashInfer's data/csrc and data/include (`flashinfer.jit.env.FLASHINFER_CSRC_DIR` /
`FLASHINFER_INCLUDE_DIR` in the image; runtime/flashinfer_pce/base/{csrc,include} for the offline tests).
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

GENERATOR_VERSION = 2
NATIVE_PBSX = (128, 256)
APPROVED = Path(__file__).resolve().parent / "APPROVED_CLOSURE.json"
CSRC_FILES = ("sparse_mla_sm120.cu", "sparse_mla_sm120_prefill.cu", "tvm_ffi_utils.h")
INCLUDE_FILES = ("flashinfer/layout.cuh",)
INCLUDE_TREE = "flashinfer/attention/sparse_mla_sm120"
# Host-side TVM-FFI glue (argument checks, stream lookup), no kernel code: hashed into the manifest and the module tag,
# but not compared against the approval (the DS image's copy was not extracted on 2026-10-27; the K8 window records it).
RECORDED_ONLY = frozenset({"csrc/tvm_ffi_utils.h"})

BINDING = """\
// Generated by runtime/flashinfer_pce/gen_pce_sources.py (DSV41_PREFILL_NATIVE_EXTRA). Do not edit.
#include "tvm_ffi_utils.h"

using tvm::ffi::Optional;

namespace flashinfer::sparse_mla_sm120 {
void PceSparseMlaSm120PagedAttention(TensorView q, TensorView kv_cache, TensorView indices,
                                     TensorView output, TensorView out_lse, double sm_scale,
                                     int64_t model_type, Optional<TensorView> topk_length,
                                     Optional<TensorView> attn_sink,
                                     Optional<TensorView> extra_kv_cache,
                                     Optional<TensorView> extra_indices,
                                     Optional<TensorView> extra_topk_length);
}  // namespace flashinfer::sparse_mla_sm120

TVM_FFI_DLL_EXPORT_TYPED_FUNC(dsv41_pce_paged_attention,
                              flashinfer::sparse_mla_sm120::PceSparseMlaSm120PagedAttention);
"""

HEADER = "// Generated by runtime/flashinfer_pce/gen_pce_sources.py from FlashInfer's {name}. Do not edit.\n"


class AnchorError(RuntimeError):
    pass


def _replace(text: str, old: str, new: str, count: int = 1, what: str = "") -> str:
    n = text.count(old)
    if n != count:
        raise AnchorError(f"anchor {what or old[:60]!r}: expected {count} occurrence(s), found {n}")
    return text.replace(old, new)


def _cut(text: str, start: str, end: str, replacement: str, must_hold: tuple, must_not_hold: tuple,
         what: str) -> str:
    """Replace text[start : end) (end exclusive) with replacement; both anchors unique, span content checked."""
    for a in (start, end):
        if text.count(a) != 1:
            raise AnchorError(f"span {what}: anchor {a[:60]!r} found {text.count(a)} times")
    i, j = text.index(start), text.index(end)
    if j <= i:
        raise AnchorError(f"span {what}: end anchor precedes start")
    span = text[i:j]
    for tok in must_hold:
        if tok not in span:
            raise AnchorError(f"span {what}: expected {tok!r} inside the removed span")
    for tok in must_not_hold:
        if tok in span:
            raise AnchorError(f"span {what}: {tok!r} must not be inside the removed span")
    return text[:i] + replacement + text[j:]


def patch_prefill(src: str) -> str:
    t = src
    # 1. full-tile path: open to 128 / 256 (and close 64 / 2, which stay on the stock module)
    t = _replace(t, "topk_extra % BI == 0 && (extra_page_block_size == 64 || extra_page_block_size == 2)) {",
                 "topk_extra % BI == 0 && (extra_page_block_size == 128 || extra_page_block_size == 256)) {",
                 what="fulltile gate")
    t = _replace(t,
                 "    if (extra_page_block_size == 64) {\n"
                 "      DISPATCH_FULLTILE_BY_NH_PBSX(64);\n"
                 "    } else {\n"
                 "      DISPATCH_FULLTILE_BY_NH_PBSX(2);\n"
                 "    }\n",
                 "    if (extra_page_block_size == 128) {\n"
                 "      DISPATCH_FULLTILE_BY_NH_PBSX(128);\n"
                 "    } else {\n"
                 "      DISPATCH_FULLTILE_BY_NH_PBSX(256);\n"
                 "    }\n", what="fulltile PBSX")
    # 2. general (topk_length / partial tiles) path
    t = _replace(t,
                 "  if (extra_page_block_size == 64) {\n"
                 "    DISPATCH_BY_NH_PBSX(64);\n"
                 "  } else if (extra_page_block_size == 2) {\n"
                 "    DISPATCH_BY_NH_PBSX(2);\n"
                 "  }\n",
                 "  if (extra_page_block_size == 128) {\n"
                 "    DISPATCH_BY_NH_PBSX(128);\n"
                 "  } else if (extra_page_block_size == 256) {\n"
                 "    DISPATCH_BY_NH_PBSX(256);\n"
                 "  }\n", what="general PBSX")
    # 3. drop the single-cache dispatchers (never used by this module; keeps the build to the dual kernels)
    t = _cut(t, "template <ModelType MT>\ninline bool dispatch_v32(", "inline bool dispatch_dsv4_dual(",
             "// dsv41 pce: single-cache dispatch (dispatch_v32, dispatch_dsv4_single) removed.\n\n",
             must_hold=("dispatch_v32", "dispatch_dsv4_single"), must_not_hold=("launch_prefill_mg_dual",),
             what="single-cache dispatchers")
    # 4. public entry: renamed, dual cache only
    t = _replace(t, "\nbool sparse_mla_prefill_dispatch(", "\nbool pce_sparse_mla_prefill_dispatch(",
                 what="dispatch definition")
    t = _cut(t, "  switch (mt) {\n    case ModelType::DSV3_2:", "}  // namespace flashinfer::sparse_mla_sm120",
             "  return false;  // dsv41 pce: dual-cache DSV4 only\n}\n\n",
             must_hold=("dispatch_v32<ModelType::DSV3_2>", "dispatch_dsv4_single("),
             must_not_hold=("dispatch_dsv4_dual(",), what="single-cache switch")
    return HEADER.format(name="sparse_mla_sm120_prefill.cu") + t


def patch_orchestrator(src: str) -> str:
    t = src
    t = _replace(t, "sparse_mla_prefill_dispatch(", "pce_sparse_mla_prefill_dispatch(", count=2,
                 what="dispatch declaration + call")
    t = _replace(t, "void SparseMlaSm120PagedAttention(", "void PceSparseMlaSm120PagedAttention(",
                 what="entry definition")
    # Without an extra cache this module has nothing to run: refuse before any launch.
    t = _replace(t, "  const bool ok = pce_sparse_mla_prefill_dispatch(",
                 "  TVM_FFI_ICHECK(page_block_size == 64 && extra_kv_ptr != nullptr &&\n"
                 "                 (extra_page_block_size == 128 || extra_page_block_size == 256))\n"
                 "      << \"dsv41 pce: main pages of 64 and native extra pages of 128 / 256 tokens only; got \"\n"
                 "      << \"page_block_size=\" << page_block_size << \" extra_page_block_size=\"\n"
                 "      << extra_page_block_size;\n"
                 "  const bool ok = pce_sparse_mla_prefill_dispatch(", what="pce guard")
    t = _replace(t, "\"Unsupported sparse-MLA prefill configuration: \"",
                 "\"dsv41 pce: unsupported sparse-MLA prefill configuration: \"", what="error text")
    return HEADER.format(name="sparse_mla_sm120.cu") + t


def _sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


class ClosureError(RuntimeError):
    pass


def closure(csrc_dir: Path, include_dir: Path) -> dict:
    """{"csrc/<f>" | "include/<f>": sha256} of every file the module compiles from (FlashInfer side)."""
    csrc_dir, include_dir = Path(csrc_dir), Path(include_dir)
    files = {f"csrc/{f}": csrc_dir / f for f in CSRC_FILES}
    files.update({f"include/{f}": include_dir / f for f in INCLUDE_FILES})
    tree = include_dir / INCLUDE_TREE
    if not tree.is_dir():
        raise ClosureError(f"no {tree}")
    for p in sorted(tree.rglob("*")):
        if p.is_file() and "__pycache__" not in p.parts:
            files[f"include/{p.relative_to(include_dir).as_posix()}"] = p
    out = {}
    for key, p in sorted(files.items()):
        try:
            out[key] = _sha(p.read_bytes())
        except OSError as e:
            raise ClosureError(f"closure file {key}: {e}") from e
    return out


def check_closure(got: dict, approved: dict, ignore=RECORDED_ONLY) -> None:
    got = {k: v for k, v in got.items() if k not in ignore}
    approved = {k: v for k, v in approved.items() if k not in ignore}
    missing = sorted(set(approved) - set(got))
    extra = sorted(set(got) - set(approved))
    changed = sorted(k for k in set(got) & set(approved) if got[k] != approved[k])
    if missing or extra or changed:
        raise ClosureError(f"FlashInfer source closure is not the approved one: changed {changed[:6]}, "
                           f"missing {missing[:6]}, unexpected {extra[:6]}")


def generate(csrc_dir: Path, include_dir: Path, out_dir: Path, approved_path: Path = APPROVED) -> dict:
    csrc_dir, include_dir, out_dir = Path(csrc_dir), Path(include_dir), Path(out_dir)
    approved = json.loads(Path(approved_path).read_text())
    clo = closure(csrc_dir, include_dir)
    check_closure(clo, approved["files"])
    src_dir = csrc_dir
    pre = (src_dir / "sparse_mla_sm120_prefill.cu").read_text()
    orc = (src_dir / "sparse_mla_sm120.cu").read_text()
    outputs = {
        "pce_prefill.cu": patch_prefill(pre),
        "pce_paged_attention.cu": patch_orchestrator(orc),
        "pce_binding.cu": BINDING,
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in outputs.items():
        (out_dir / name).write_text(text)
    digest = hashlib.sha256()
    digest.update(f"generator {GENERATOR_VERSION}\0".encode())
    for name in sorted(outputs):
        digest.update(name.encode() + b"\0" + outputs[name].encode() + b"\0")
    for key in sorted(clo):
        digest.update(f"{key}\0{clo[key]}\0".encode())
    manifest = {
        "generator_version": GENERATOR_VERSION,
        "native_extra_page_block_sizes": list(NATIVE_PBSX),
        "approved_flashinfer": approved.get("flashinfer"),
        "closure": clo,
        "inputs": {
            "sparse_mla_sm120_prefill.cu": _sha(pre.encode()),
            "sparse_mla_sm120.cu": _sha(orc.encode()),
        },
        "outputs": {name: _sha(text.encode()) for name, text in sorted(outputs.items())},
        "module_tag": digest.hexdigest()[:12],
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n")
    return manifest


def main(argv) -> int:
    if len(argv) == 4 and argv[1] == "--approve":
        try:
            print(json.dumps({"flashinfer": "FILL IN: version + git commit of the reviewed tree",
                              "files": closure(Path(argv[2]), Path(argv[3]))}, indent=1, sort_keys=True))
        except ClosureError as e:
            print(f"PCE GEN FAIL: {e}", file=sys.stderr)
            return 1
        return 0
    if len(argv) != 4:
        print("usage: gen_pce_sources.py CSRC_DIR INCLUDE_DIR OUT_DIR | --approve CSRC_DIR INCLUDE_DIR", file=sys.stderr)
        return 2
    try:
        m = generate(Path(argv[1]), Path(argv[2]), Path(argv[3]))
    except (AnchorError, ClosureError, OSError, ValueError, KeyError) as e:
        print(f"PCE GEN FAIL: {e}", file=sys.stderr)
        return 1
    print(f"PCE GEN OK module_tag={m['module_tag']} closure={len(m['closure'])} files ({m['approved_flashinfer']})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
